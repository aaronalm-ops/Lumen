package app.lumen.player.remote

import android.accounts.Account
import android.content.Context
import android.content.Intent
import app.lumen.player.diag.RingLog
import com.google.android.gms.auth.api.identity.AuthorizationRequest
import com.google.android.gms.auth.api.identity.ClearTokenRequest
import com.google.android.gms.auth.api.identity.AuthorizationResult
import com.google.android.gms.auth.api.identity.Identity
import com.google.android.gms.common.api.Scope
import com.google.android.gms.tasks.Task
import com.google.android.gms.tasks.Tasks
import org.json.JSONObject
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URL
import java.util.concurrent.TimeUnit

/**
 * 0.8.1: reads a YouTube or YouTube Music playlist so its songs can be picked into Lumen one by
 * one. YouTube Data API v3 with the owner's own Google account (scope youtube.readonly, asked once
 * through the same Play Services sheet as Drive), so his private playlists and albums work too.
 * Lumen only reads: titles, artists, lengths and video ids. Nothing is played or downloaded here.
 *
 * Calls: playlists.list (the title, 1 unit), playlistItems.list (50 per page, 1 unit each) and
 * videos.list (lengths, 50 per call, 1 unit each). The daily allowance is 10,000 units.
 */
class YoutubeApi(private val context: Context) {

    data class Track(val videoId: String, val title: String, val artist: String, val durationMs: Long)

    data class Playlist(val id: String, val title: String, val tracks: List<Track>)

    data class PlaylistSummary(val id: String, val title: String, val trackCount: Int, val privacy: String)

    class NotConfigured(message: String) : IOException(message)

    class NeedsSignIn : IOException("Sign in to YouTube")
    private class PlaylistUnavailable : IOException("This playlist is private, unavailable, or generated by YouTube. Check the link or reconnect with its owner account")

    @Volatile
    private var cachedToken: String? = null

    @Volatile
    private var cachedAt = 0L

    private val preferences = context.getSharedPreferences("youtube_account", Context.MODE_PRIVATE)
    @Volatile private var selectedAccount: Account? = preferences.getString("account", null)?.let { Account(it, "com.google") }

    // Keep YouTube and Drive grants separate. This is a required SDK API, never a best-effort reflection call.
    private fun request(selectAccount: Boolean): AuthorizationRequest {
        val builder = AuthorizationRequest.builder()
            .setRequestedScopes(listOf(Scope(SCOPE)))
            .setOptOutIncludingGrantedScopes(true)
        if (selectAccount) builder.setPrompt(AuthorizationRequest.Prompt.SELECT_ACCOUNT)
        else selectedAccount?.let { builder.setAccount(it) }
        return builder.build()
    }

    /** Account selection is explicit on Connect; silent refresh stays with the chosen account. */
    fun authorizeTask(selectAccount: Boolean = false): Task<AuthorizationResult> =
        Identity.getAuthorizationClient(context).authorize(request(selectAccount))

    fun resultFromIntent(data: Intent?): AuthorizationResult =
        Identity.getAuthorizationClient(context).getAuthorizationResultFromIntent(data)

    fun accept(result: AuthorizationResult): String? {
        if (!result.grantedScopes.orEmpty().contains(SCOPE)) throw NeedsSignIn()
        val token = result.accessToken?.takeIf { it.isNotBlank() } ?: return null
        @Suppress("DEPRECATION")
        val account = result.toGoogleSignInAccount()?.account
        if (account != null) {
            selectedAccount = account
            preferences.edit().putString("account", account.name).apply()
        }
        cachedToken = token
        cachedAt = System.currentTimeMillis()
        return token
    }

    /** A token without any UI, or [NeedsSignIn]. Never on the main thread. */
    private fun tokenBlocking(): String {
        cachedToken?.let { if (System.currentTimeMillis() - cachedAt < TOKEN_REUSE_MS) return it }
        val result = Tasks.await(authorizeTask(), 20, TimeUnit.SECONDS)
        if (result.hasResolution()) throw NeedsSignIn()
        return accept(result) ?: throw NeedsSignIn()
    }

    /** Owned playlists, including private ones. Saved playlists and generated mixes need a link. */
    fun fetchMyPlaylists(): List<PlaylistSummary> = withAccount { it.playlists() }

    fun fetchPlaylist(listId: String, apiKey: String? = null): Playlist {
        // Prefer the authorised account, so private playlists never depend on the Gemini key.
        try {
            return withAccount { it.playlist(listId) }
        } catch (e: Exception) {
            // Preserve public-link import even when account authorisation is unavailable.
            if (apiKey.isNullOrBlank() || (e !is NeedsSignIn && e !is java.util.concurrent.ExecutionException)) throw e
            try {
                return catalog(Auth.Key(apiKey)).playlist(listId)
            } catch (unavailable: PlaylistUnavailable) {
                throw NeedsSignIn()
            }
        }
    }

    private fun <T> withAccount(block: (YoutubeCatalog) -> T): T {
        val token = tokenBlocking()
        try {
            return block(catalog(Auth.Bearer(token)))
        } catch (e: NeedsSignIn) {
            cachedToken = null
            Tasks.await(Identity.getAuthorizationClient(context).clearToken(
                ClearTokenRequest.builder().setToken(token).build()), 5, TimeUnit.SECONDS)
            return block(catalog(Auth.Bearer(tokenBlocking())))
        }
    }

    private sealed class Auth {
        class Bearer(val token: String) : Auth()
        class Key(val key: String) : Auth()
    }

    private fun catalog(auth: Auth) = YoutubeCatalog { path -> getJson(auth, "$API/$path") }

    private fun getJson(token: Auth, url: String): JSONObject {
        val c = URL(url).openConnection() as HttpURLConnection
        c.connectTimeout = 15_000
        c.readTimeout = 30_000
        when (token) {
            is Auth.Bearer -> c.setRequestProperty("Authorization", "Bearer ${token.token}")
            is Auth.Key -> c.setRequestProperty("x-goog-api-key", token.key)
        }
        try {
            val code = c.responseCode
            if (code == 401) {
                cachedToken = null
                throw NeedsSignIn()
            }
            if (code !in 200..299) {
                val body = c.errorStream?.bufferedReader()?.use { it.readText() }.orEmpty()
                val reason = try {
                    JSONObject(body).optJSONObject("error")?.optJSONArray("errors")?.optJSONObject(0)?.optString("reason").orEmpty()
                } catch (_: Throwable) {
                    ""
                }
                val message = try {
                    JSONObject(body).optJSONObject("error")?.optString("message").orEmpty()
                } catch (_: Throwable) {
                    ""
                }
                RingLog.w("youtube", "API request failed: $code $reason")
                if (code == 403 && (reason == "accessNotConfigured" || message.contains("has not been used", true) || message.contains("disabled", true))) {
                    throw NotConfigured("YouTube Data API is not switched on in Google Cloud yet")
                }
                if (code == 403 && (reason.contains("insufficient", true) || message.contains("scope", true))) throw NeedsSignIn()
                if (reason == "youtubeSignupRequired") throw IOException("This Google account has no YouTube channel. Connect the account used in YouTube Music")
                if (code == 404 || reason == "playlistForbidden") throw PlaylistUnavailable()
                if (code == 403 && reason.contains("quota", true)) throw IOException("YouTube's daily allowance is used up. Try again tomorrow")
                throw IOException("YouTube could not read this playlist ($code ${reason.ifBlank { "request failed" }}). Try again or reconnect")
            }
            return JSONObject(c.inputStream.bufferedReader().use { it.readText() })
        } finally {
            c.disconnect()
        }
    }

    companion object {
        const val SCOPE = "https://www.googleapis.com/auth/youtube.readonly"
        private const val API = "https://www.googleapis.com/youtube/v3"
        private const val TOKEN_REUSE_MS = 45L * 60 * 1000

        fun connectionError(error: Throwable): String {
            val causes = generateSequence(error) { it.cause }.take(8).toList()
            val detail = causes.mapNotNull { it.message }.joinToString(" ")
            return when {
                detail.contains("scope", true) && (detail.contains("together", true) || detail.contains("combine", true)) ->
                    "Google combined YouTube and Drive permissions. Update Google Play services, then reconnect YouTube. Your Drive connection is kept"
                causes.any { it is java.net.UnknownHostException || it is java.net.SocketTimeoutException } ->
                    "Could not reach Google. Check your connection and try again"
                detail.contains("access_denied", true) ->
                    "Google denied access. Use the account from YouTube Music and allow read access. If access is blocked, check the OAuth app's test users and publishing status"
                causes.any { it is com.google.android.gms.common.api.ApiException && it.statusCode == 10 } ->
                    "Google sign-in is not configured for this app build. The Android OAuth client must match Lumen's package and signing certificate"
                causes.any { it is NeedsSignIn } -> "Connect YouTube and allow Lumen to read your playlists"
                causes.lastOrNull() is IOException -> causes.last().message ?: "Could not read YouTube. Try again"
                else -> "Could not connect to YouTube. Try again or reconnect your account"
            }
        }

        /** "PT3M41S" to milliseconds. */
        fun isoDurationMs(iso: String): Long {
            val m = Regex("P(?:(\\d+)D)?T?(?:(\\d+)H)?(?:(\\d+)M)?(?:(\\d+)S)?").matchEntire(iso) ?: return 0L
            val (d, h, min, s) = m.destructured
            return (((d.toLongOrNull() ?: 0L) * 24 + (h.toLongOrNull() ?: 0L)) * 3600 +
                (min.toLongOrNull() ?: 0L) * 60 + (s.toLongOrNull() ?: 0L)) * 1000
        }
    }
}
